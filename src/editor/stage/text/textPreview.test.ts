const flat = (l: LaidText | null): number[] =>
  l === null
    ? new Array(20).fill(0)
    : [
        1,
        l.fontPx,
        l.subPx,
        l.plate[0],
        l.plate[1],
        l.plate[2],
        l.plate[3],
        l.mainBaseline[0],
        l.mainBaseline[1],
        l.subBaseline[0],
        l.subBaseline[1],
        l.rule[0],
        l.rule[1],
        l.rule[2],
        l.rule[3],
        l.alpha,
        l.reveal === null ? -1 : l.reveal,
        l.scale,
        l.shift[0],
        l.shift[1],
      ];

describe("textPreview mirrors textlayout", () => {
  it("pins the same forty eight layouts", () => {
    for (let i = 0; i < 48; i++) {
      const [item, ow, oh, t] = testCase(i);
      const got = flat(layOne(item, ACCENT, ow, oh, t));
      const want = TABLE[i].trim().split(/\s+/).map(Number);
      expect(want, `row ${i} malformed`).toHaveLength(20);
      for (let k = 0; k < 20; k++) {
        expect(got[k], `case ${i} field ${k}`).toBeCloseTo(want[k], 3);
      }
    }
  });

  it("returns null outside the span and for an empty item", () => {
    const [item, ow, oh] = testCase(7);
    expect(layOne(item, ACCENT, ow, oh, 999)).toBeNull();
    expect(layOne(item, ACCENT, ow, oh, 5000)).toBeNull();
    expect(layOne({ ...item, text: "  ", sub: null }, ACCENT, ow, oh, 3000)).toBeNull();
  });

  it("reveals a typewriter on the same fixed cadence", () => {
    const [base, ow, oh] = testCase(0);
    const item: TextItem = {
      ...base,
      text: "0123456789012345678901234567890123456789",
      sub: null,
      anim_in: "typewriter",
      in_ms: 1200,
      start_ms: 0,
      end_ms: 6000,
    };
    const at = (t: number) => layOne(item, ACCENT, ow, oh, t)!.reveal;
    expect([at(0), at(300), at(600), at(1200), at(3000)]).toEqual([0, 10, 20, 40, 40]);
  });

  it("keeps array order and drops the ones that are not live", () => {
    const [a, ow, oh] = testCase(0);
    const [b] = testCase(5);
    const [c] = testCase(9);
    const live = laidTexts([a, { ...b, start_ms: 9000, end_ms: 12000 }, c], ACCENT, ow, oh, 3000);
    expect(live).toHaveLength(2);
  });
});
